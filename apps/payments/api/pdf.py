from io import BytesIO

from django.http import HttpResponse
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas


def payment_pdf_response(
    *,
    payment,
    document_type: str,
) -> HttpResponse:
    if document_type not in {"invoice", "receipt"}:
        raise ValueError("Unsupported payment document type.")

    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4

    title = "CarRent TN Invoice"
    number = payment.invoice_number

    if document_type == "receipt":
        title = "CarRent TN Receipt"
        number = payment.receipt_number or ""

    y = height - 70
    pdf.setFont("Helvetica-Bold", 18)
    pdf.drawString(60, y, title)
    y -= 34

    pdf.setFont("Helvetica", 10)
    lines = [
        f"Document number: {number}",
        f"Booking: {payment.booking_id}",
        f"Agency: {payment.booking.agency.agency_name}",
        f"Customer: {payment.booking.customer.full_name}",
        f"Payment method: {payment.get_method_display()}",
        f"Payment status: {payment.get_status_display()}",
        f"Rental amount: {payment.rental_amount} TND",
        f"Security deposit: {payment.deposit_amount} TND",
    ]

    if payment.paid_at:
        lines.append(
            f"Paid at: {payment.paid_at.strftime('%Y-%m-%d %H:%M')}"
        )

    for line in lines:
        pdf.drawString(60, y, line)
        y -= 20

    pdf.setFont("Helvetica-Oblique", 9)
    pdf.drawString(
        60,
        55,
        "Generated by CarRent TN. No tax amount is assumed by the MVP.",
    )

    pdf.showPage()
    pdf.save()

    payload = buffer.getvalue()
    response = HttpResponse(
        payload,
        content_type="application/pdf",
    )
    response["Content-Disposition"] = (
        f'inline; filename="{document_type}-{number}.pdf"'
    )
    response["Cache-Control"] = "private, no-store, max-age=0"
    return response
