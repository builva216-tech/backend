import hashlib
import hmac
import logging
import secrets
import uuid
from datetime import timedelta

from django.conf import settings
from django.contrib.auth.hashers import check_password, make_password
from django.contrib.auth.password_validation import validate_password
from django.core.exceptions import ValidationError as DjangoValidationError
from django.core.mail import send_mail
from django.db import transaction
from django.utils import timezone
from django.utils.crypto import constant_time_compare, salted_hmac
from rest_framework.exceptions import ValidationError
from rest_framework_simplejwt.token_blacklist.models import (
    BlacklistedToken,
    OutstandingToken,
)

from apps.accounts.models import (
    AccountAuditEvent,
    PasswordRecoveryChallenge,
    User,
    UserRole,
)

logger = logging.getLogger(__name__)
GENERIC_MESSAGE = (
    "If an eligible account exists, a recovery code will be sent to that email."
)
INVALID_CODE = "Invalid or expired recovery code. Request a new code if needed."


def _fingerprint(value, purpose):
    return salted_hmac(purpose, value, algorithm="sha256").hexdigest()


def recovery_code(challenge, user):
    # The random UUID is a nonce. The code can be regenerated by the mail worker
    # without persisting an unencrypted recovery secret or returning it via API.
    digest = hmac.new(
        settings.SECRET_KEY.encode(),
        f"password-recovery:{challenge.id}:{user.password}".encode(),
        hashlib.sha256,
    ).digest()
    return f"{int.from_bytes(digest[:8], 'big') % 100_000_000:08d}"


def request_password_recovery(*, email, purpose):
    email = email.strip().lower()
    now = timezone.now()
    email_fingerprint = _fingerprint(email, "recovery-email")
    challenge = PasswordRecoveryChallenge(
        id=uuid.uuid4(),
        purpose=purpose,
        email_fingerprint=email_fingerprint,
        expires_at=now + timedelta(minutes=15),
        next_delivery_at=now,
    )
    with transaction.atomic():
        user = (
            User.objects.select_for_update()
            .filter(email__iexact=email, is_active=True)
            .first()
        )
        eligible = bool(
            user
            and user.has_usable_password()
            and (
                (purpose == "admin" and user.role == UserRole.ADMIN and user.is_staff)
                or (
                    purpose == "mobile"
                    and user.role in [UserRole.CUSTOMER, UserRole.AGENCY]
                )
            )
        )
        recent = PasswordRecoveryChallenge.objects.filter(
            email_fingerprint=email_fingerprint,
            created_at__gte=now - timedelta(hours=1),
        )
        permitted = (
            recent.count() < 5
            and not recent.filter(created_at__gte=now - timedelta(seconds=60)).exists()
        )
        if eligible and permitted:
            challenge.user = user
            challenge.password_fingerprint = _fingerprint(
                user.password, "recovery-password"
            )
            code = recovery_code(challenge, user)
            PasswordRecoveryChallenge.objects.filter(
                user=user, purpose=purpose, used_at__isnull=True
            ).update(expires_at=now)
        else:
            # Persist the same request shape and perform the same password-hash
            # work for unknown, blocked, wrong-role and rate-limited accounts.
            code = f"{secrets.randbelow(100_000_000):08d}"
            challenge.password_fingerprint = _fingerprint(
                secrets.token_hex(32), "recovery-password"
            )
        challenge.code_hash = make_password(code)
        challenge.save()
    return {
        "challengeId": str(challenge.id),
        "message": GENERIC_MESSAGE,
        "expiresInSeconds": 900,
        "resendAfterSeconds": 60,
    }


def confirm_password_recovery(*, challenge_id, code, password, purpose):
    accepted = False
    reference = (
        PasswordRecoveryChallenge.objects.filter(id=challenge_id, purpose=purpose)
        .values("user_id")
        .first()
    )
    with transaction.atomic():
        # Match the request path's lock order: user, then challenge.
        user = (
            User.objects.select_for_update()
            .filter(id=reference["user_id"], is_active=True)
            .first()
            if reference
            else None
        )
        challenge = (
            PasswordRecoveryChallenge.objects.select_for_update()
            .filter(id=challenge_id, purpose=purpose)
            .first()
        )
        if (
            challenge
            and challenge.used_at is None
            and challenge.expires_at > timezone.now()
            and challenge.attempts_remaining
        ):
            valid_user = bool(
                user
                and constant_time_compare(
                    challenge.password_fingerprint,
                    _fingerprint(user.password, "recovery-password"),
                )
                and constant_time_compare(
                    challenge.email_fingerprint,
                    _fingerprint(user.email.strip().lower(), "recovery-email"),
                )
                and (
                    (
                        purpose == "admin"
                        and user.role == UserRole.ADMIN
                        and user.is_staff
                    )
                    or (
                        purpose == "mobile"
                        and user.role in [UserRole.CUSTOMER, UserRole.AGENCY]
                    )
                )
            )
            valid_code = check_password(code, challenge.code_hash)
            if valid_user and valid_code:
                try:
                    validate_password(password, user=user)
                except DjangoValidationError as exc:
                    raise ValidationError({"newPassword": list(exc.messages)}) from exc
                user.set_password(password)
                user.is_email_verified = True
                user.save(update_fields=["password", "is_email_verified", "updated_at"])
                challenge.used_at = timezone.now()
                challenge.delivery_attempts = 0
                challenge.next_delivery_at = timezone.now()
                challenge.save(
                    update_fields=["used_at", "delivery_attempts", "next_delivery_at"]
                )
                PasswordRecoveryChallenge.objects.filter(
                    user=user, used_at__isnull=True
                ).exclude(id=challenge.id).update(expires_at=timezone.now())
                for token in OutstandingToken.objects.filter(user=user):
                    BlacklistedToken.objects.get_or_create(token=token)
                AccountAuditEvent.objects.create(
                    subject=user, action="password_recovered"
                )
                accepted = True
            else:
                challenge.attempts_remaining -= 1
                challenge.save(update_fields=["attempts_remaining"])
    # Incorrect attempts commit before an API error is raised. An outer atomic
    # decorator here would incorrectly roll back brute-force protection.
    if not accepted:
        raise ValidationError({"code": [INVALID_CODE]})
    return {"message": "Password updated. Sign in with your new password."}


def deliver_recovery_email(challenge_id):
    with transaction.atomic():
        challenge = (
            PasswordRecoveryChallenge.objects.select_for_update()
            .filter(id=challenge_id)
            .first()
        )
        if not challenge or not challenge.user_id:
            return False
        user = User.objects.filter(id=challenge.user_id, is_active=True).first()
        if not user:
            return False
        now = timezone.now()
        if challenge.delivery_attempts >= 5 or (
            challenge.next_delivery_at and challenge.next_delivery_at > now
        ):
            return False
        notification = challenge.used_at is not None
        if notification:
            if challenge.notification_sent_at is not None:
                return False
            subject = "Your CarRent TN password was changed"
            message = "Your account password was changed through password recovery. If this was not you, recover your account immediately and contact support."
        else:
            if (
                challenge.emailed_at
                or challenge.expires_at <= now
                or not challenge.attempts_remaining
            ):
                return False
            if not constant_time_compare(
                challenge.password_fingerprint,
                _fingerprint(user.password, "recovery-password"),
            ):
                return False
            if not constant_time_compare(
                challenge.email_fingerprint,
                _fingerprint(user.email.strip().lower(), "recovery-email"),
            ):
                return False
            subject = "Your CarRent TN recovery code"
            message = f"Your recovery code is {recovery_code(challenge, user)}.\n\nEnter it in the {'admin portal' if challenge.purpose == 'admin' else 'CarRent TN app'}. It expires 15 minutes after your request. Do not share it. If you did not request this, ignore this email."
        challenge.delivery_attempts += 1
        try:
            sent = send_mail(
                subject,
                message,
                settings.DEFAULT_FROM_EMAIL,
                [user.email],
                fail_silently=False,
            )
            if sent != 1:
                raise RuntimeError("Mail backend did not accept delivery")
        except Exception:  # noqa: BLE001 - mail adapters can raise provider-specific errors
            # Never log mail bodies, codes, credentials or recipient addresses.
            logger.warning("Password recovery email delivery failed; retry queued")
            challenge.next_delivery_at = now + timedelta(
                seconds=60 * challenge.delivery_attempts
            )
            challenge.save(update_fields=["delivery_attempts", "next_delivery_at"])
            return False
        if notification:
            challenge.notification_sent_at = now
        else:
            challenge.emailed_at = now
        challenge.save(
            update_fields=["delivery_attempts", "emailed_at", "notification_sent_at"]
        )
        return True
